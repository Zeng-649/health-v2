function recoveryFallback(opts) {
  opts = opts || {};
  var method = opts.method || "内固定手术";
  var timing = opts.timing || "1 周内";
  var age = opts.age || 55;
  var isSurgery = method.indexOf("手术") !== -1;

  var head = "**个性化恢复计划**（" + method + " · 距开始治疗 " + timing + " · " + age + " 岁）\n\n";

  var stageIntro = isSurgery
    ? "以下按「炎症期 / 修复期 / 重塑期 / 康复期」四阶段安排术后康复："
    : "保守治疗以卧床制动与支具保护为基础，四阶段时间轴整体后移，请在医师指导下完成各阶段目标：";

  var md = head + stageIntro + "\n\n";
  RECOVERY_STAGES.forEach(function (s, i) {
    var timeText = isSurgery ? s.time : s.time.replace("术后", "伤后");
    md += "### 第 " + (i + 1) + " 阶段 · " + s.stage + "（" + timeText + "）\n";
    md += "- **康复目标**：" + s.goal + "\n";
    md += "- **锻炼建议**：" + s.exercise + "\n";
    md += "- **饮食营养**：" + s.diet + "\n";
    md += "- **注意事项**：" + s.notes + "\n";
    md += "- **复查节点**：" + s.review + "\n\n";
  });
  md += "**治疗方式**：" + method + "｜**距开始治疗时间**：" + timing + "｜**年龄**：" + age + " 岁\n";
  if (!isSurgery) {
    md += "保守治疗期间若出现疼痛加重、畸形或神经症状，应及时复评是否转为手术治疗。";
  } else if (age >= 60) {
    md += "年龄 ≥60 岁患者建议同步抗骨质疏松治疗并加强防跌倒训练。";
  }
  return md;
}